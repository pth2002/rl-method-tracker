"""Write FRAMEWORKS.md: for each framework, where to read its contribution rules, where its RL
algorithms live, how recent methods came in, and what happened to proposals for other methods.

Needs the framework clones in .cache/repos for the file lookups.

  python tools/frameworks_doc.py
"""
from __future__ import annotations

import json
import re
import subprocess
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
GEN = ROOT / "data" / "generated"
REPOS = ROOT / ".cache" / "repos"
LABEL = {"verl": "verl", "trl": "TRL", "openrlhf": "OpenRLHF", "nemo-rl": "NeMo-RL", "roll": "ROLL",
         "slime": "slime", "areal": "AReaL"}
GUIDES = ["CONTRIBUTING.md", ".github/CONTRIBUTING.md", "docs/CONTRIBUTING.md", ".github/PULL_REQUEST_TEMPLATE.md",
          "AGENTS.md"]
SURFACE_NAME = {"adv_estimator": "advantage estimators", "policy_loss": "policy losses", "loss_agg_mode": "loss aggregation",
                "options": "configuration switches", "recipe": "recipes", "trainer": "trainers",
                "grpo_loss_type": "GRPO loss types", "grpo_options": "GRPO switches", "experimental": "experimental trainers",
                "policy_loss_type": "policy loss types", "pg_variant": "policy-gradient variants",
                "algo_configs": "algorithm configurations", "fixes": "listed code changes",
                "pipelines": "listed pipelines"}
OUTCOME = {"open_no_reply": "open, no reply from a prior merger", "open_engaged": "open, under discussion",
           "declined": "declined", "redirected": "redirected", "closed_inactive": "closed as inactive",
           "closed_no_comment": "closed without comment", "withdrawn": "withdrawn by proposer",
           "stale_cleanup": "closed in stale cleanup", "resolved_otherwise": "closed by another change"}


def jl(p: Path) -> list[dict]:
    return [json.loads(l) for l in p.read_text(encoding="utf-8").splitlines() if l.strip()] if p.exists() else []


def tree(repo: Path, sha: str) -> set[str]:
    out = subprocess.run(["git", "-C", str(repo), "ls-tree", "-r", "--name-only", sha], capture_output=True,
                         text=True, encoding="utf-8", errors="replace").stdout
    return set(out.splitlines())


def submodules(repo: Path, sha: str) -> dict[str, str]:
    """Submodule path -> link to the pinned commit in the submodule's own repository."""
    run = lambda *a: subprocess.run(["git", "-C", str(repo), *a], capture_output=True, text=True,
                                    encoding="utf-8", errors="replace").stdout
    urls = dict(re.findall(r"path = (\S+)\s+url = (\S+)", run("show", f"{sha}:.gitmodules")))
    out = {}
    for line in run("ls-tree", "-r", sha).splitlines():
        mode, _, commit, path = line.split(None, 3)
        if mode == "160000" and path in urls:
            out[path] = f"{urls[path].removesuffix('.git')}/tree/{commit}"
    return out


def main() -> None:
    cfg = yaml.safe_load((ROOT / "config" / "frameworks.yaml").read_text(encoding="utf-8"))["frameworks"]
    head = json.loads((GEN / "framework_head.json").read_text(encoding="utf-8"))
    names = {m["id"]: m["name"].split(" (")[0] for m in yaml.safe_load((ROOT / "data" / "methods.yaml").read_text(encoding="utf-8"))}
    process = json.loads((GEN / "process" / "summary.json").read_text(encoding="utf-8"))
    summary, review = process["by_framework"], process["review"]["by_framework"]
    landings = jl(GEN / "process" / "landings.jsonl")
    attempts = jl(GEN / "process" / "attempts_coded.jsonl")
    repo_url = {fw: spec["url"].rstrip("/") for fw, spec in cfg.items()}

    out = ["# Bringing a method to a framework", "",
           "For each framework: where its contribution rules are, where its RL algorithms live, how recent methods",
           "came in, and what happened to public proposals for methods that no framework included.",
           "Links point at the snapshot commit used in the report. Generated by `tools/frameworks_doc.py`.", "",
           "A prior merger is someone who had merged a pull request in the framework before the event. It stands in",
           "for maintainers and misses reviewers without merge rights.", ""]
    for fw in ["verl", "trl", "openrlhf", "nemo-rl", "roll", "slime", "areal"]:
        info, base = head[fw], repo_url[fw]
        sha = info["head_sha"]
        out += [f"## {LABEL[fw]}", "", f"Repository: {base} (snapshot `{sha[:10]}`, {info['head_date']})", ""]
        files, subs = tree(REPOS / fw, sha), submodules(REPOS / fw, sha)
        guides = [g for g in GUIDES if g in files]
        if guides:
            out.append("Contribution rules: " + ", ".join(f"[{g}]({base}/blob/{sha}/{g})" for g in guides))
        else:
            out.append("Contribution rules: no contribution guide at the snapshot.")
        out += ["", "Where RL algorithms live:", ""]
        specs = [(fw, cfg[fw])] + ([("verl_recipe", cfg["verl_recipe"])] if fw == "verl" else [])
        for name, spec in specs:
            s_sha, s_base = head[name]["head_sha"], repo_url[name]
            for surf in spec["surfaces"]:
                if surf["kind"] == "defaults":
                    continue
                if surf["kind"] == "values":
                    paths = sorted({p for pat in surf["patterns"] for p in pat["paths"]})
                elif surf["kind"] == "flags":
                    paths = surf["scope"]
                elif surf["kind"] in ("dirs", "files"):
                    paths = [surf["dir"]]
                else:
                    paths = sorted({e["path"] for e in surf["entries"]})
                shown = []
                for pth in paths:
                    if pth in ("", "."):
                        shown.append(f"[repository root]({s_base}/tree/{s_sha})")
                    elif name == fw and pth in subs:
                        shown.append(f"[`{pth}`]({subs[pth]}) (submodule)")
                    elif pth in files or name != fw:
                        kind = "blob" if "." in pth.split("/")[-1] else "tree"
                        shown.append(f"[`{pth}`]({s_base}/{kind}/{s_sha}/{pth})")
                    else:
                        kind = "blob" if "." in pth.split("/")[-1] else "tree"
                        if any(f.startswith(pth + "/") for f in files) or pth in files:
                            shown.append(f"[`{pth}`]({s_base}/{kind}/{s_sha}/{pth})")
                if shown:
                    where = "verl-recipe " if name == "verl_recipe" else ""
                    out.append(f"- {where}{SURFACE_NAME.get(surf['id'], surf['id'])} ({surf['tier'].replace('_', ' ')}): "
                               + ", ".join(shown))
        q = summary.get(fw, {})
        out += ["", f"How recent methods came in: {q.get('landing_prs', 0)} pull requests brought methods with a source "
                f"from 2025 or later into {LABEL[fw]}. Prior mergers opened {q.get('author_prior_merger', 0)} of them, "
                f"and the median time from opening to merge was {q.get('median_days_open', '--')} days.", ""]
        rv = review.get(fw, {}).get("merged")
        if rv and rv["n"]:
            r, d = rv["raised"], rv["driver"]
            out += [f"What review raised in these {rv['n']} pull requests: someone other than the proposer replied in "
                    f"{rv['human_discussion']}. Concerns about design came up in {r['design']}, about tests and "
                    f"documentation in {r['completeness']}, about evidence in {r['evidence']} and about placement in "
                    f"{r['placement']}. Concerns about maintenance burden or demand came up in {rv['demand_or_surface']}. "
                    f"Reviewers asked for training results in {rv['results_requested']}, and the proposer revised the "
                    f"change in {d.get('proposer', 0) + d.get('both', 0)}.", ""]
        mine = sorted([r for r in landings if r["framework"] == fw and r.get("pr_author")],
                      key=lambda r: r["date"], reverse=True)
        seen, ex = set(), []
        for r in mine:
            k = (r["repo"], r["pr"])
            if k in seen:
                continue
            seen.add(k)
            ex.append(f"- {r['date']}: {names.get(r['method'], r['method'])}, "
                      f"[{'verl-recipe ' if r['repo'] == 'verl_recipe' else ''}PR #{r['pr']}]({repo_url[r['repo']]}/pull/{r['pr']})")
            if len(ex) == 5:
                break
        if ex:
            out += ["Recent examples:", ""] + ex + [""]
        mine_att = sorted([a for a in attempts if a["framework"] in ((fw, "verl_recipe") if fw == "verl" else (fw,))],
                          key=lambda a: a["number"])
        if mine_att:
            out += ["Public proposals for methods that no framework included:", "",
                    "| Method | Thread | Outcome | Reasons a maintainer stated |", "|---|---|---|---|"]
            for a in mine_att:
                kind = "pull" if a["type"] == "pr" else "issues"
                if a["framework"] == "trl" and a["number"] == 3291:
                    url, label = f"{repo_url['trl']}/discussions/3291", "discussion #3291"
                else:
                    url = f"{repo_url[a['framework']]}/{kind}/{a['number']}"
                    label = ("PR" if a["type"] == "pr" else "issue") + f" #{a['number']}"
                reasons = ", ".join(a["reasons"]) or "none stated"
                out.append(f"| {a['method']} | [{label}]({url}) | {OUTCOME[a['outcome']]} | {reasons} |")
            out.append("")
    (ROOT / "FRAMEWORKS.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote FRAMEWORKS.md")


if __name__ == "__main__":
    main()
